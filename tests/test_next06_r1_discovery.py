def test_additional_project_root_is_only_a_suggestion(tmp_path):
    src,dst,path=example(tmp_path)
    (src/'services/api').mkdir(parents=True)
    (src/'services/api/pyproject.toml').write_text('[project]\nname="api"\nversion="1"\n')
    git(src,'add','.');git(src,'commit','-qm','separate-service')
    repin(path,src)
    result=discover(path)
    extra=result['additional_move_suggestions']
    assert any(x['from']=='services/api' and x['to'] is None and x['review_required'] for x in extra)
    assert all(x['review_required'] and x['replacement'] is None for x in result['rewrite_suggestions'])
