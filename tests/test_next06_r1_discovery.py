"""NEXT-06-R1 discovery contracts: disposable repositories; no real repo mutation."""
import hashlib
import json
from pathlib import Path
import subprocess

import pytest

from devtool.repository_extraction import ExtractionBlocked, run
from devtool.repository_extraction_discovery import discover


def git(root, *args):
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, check=True).stdout.strip()


def example(tmp_path, *, reference='apps/xbs', consumer='', generated=True):
    src, dst = tmp_path/'src', tmp_path/'dst'
    for root in (src, dst):
        root.mkdir()
        git(root, 'init', '-q')
        git(root, 'config', 'user.name', 'QA')
        git(root, 'config', 'user.email', 'qa@example.org')
        git(root, 'remote', 'add', 'origin', f'https://example.org/{root.name}.git')
        (root/'README.md').write_text('unrelated\n')
    (src/'.gitignore').write_text('*.tmp\n')
    (src/'apps/xbs').mkdir(parents=True)
    (src/'apps/xbs/go.mod').write_text('module example.org/xbs\n')
    (src/'apps/xbs/main.go').write_text('package main\n')
    (src/'.github/workflows').mkdir(parents=True)
    (src/'.github/workflows/build.yml').write_text('steps:\n  - run: cd '+reference+'\n')
    (src/'notes.md').write_text('reference: '+reference+'\n')
    (dst/'consumer.sh').write_text(consumer+'\n')
    for root in (src, dst):
        git(root,'add','.')
        git(root,'commit','-qm','base')
    if generated:
        (src/'apps/xbs/output.tmp').write_text('generated bytes')
    def identity(root):
        return {'path':str(root), 'head':git(root,'rev-parse','HEAD'),
                'tree':git(root,'rev-parse','HEAD^{tree}'),
                'branch':git(root,'symbolic-ref','--short','HEAD'),
                'remote':'origin', 'remote_url':f'https://example.org/{root.name}.git'}
    config={'schema':'devtool.repo-extraction.v1', 'source':identity(src), 'destination':identity(dst),
            'moves':[{'from':'apps/xbs','to':'.'}], 'source_rewrites':[],
            'forbid_source_references':['apps/xbs']}
    path=tmp_path/'draft.json';path.write_text(json.dumps(config))
    return src,dst,path


def repin(path, root):
    obj=json.loads(path.read_text())
    obj['source']['head']=git(root,'rev-parse','HEAD')
    obj['source']['tree']=git(root,'rev-parse','HEAD^{tree}')
    path.write_text(json.dumps(obj))


def test_evidence_exact_lines_and_readonly(tmp_path):
    src,dst,path=example(tmp_path)
    old=(git(src,'status','--porcelain'),git(dst,'status','--porcelain'),git(src,'rev-parse','HEAD'))
    result=run('discover',path,tmp_path/'should_not_exist')
    assert result['ok'] and result['state']=='REVIEW_REQUIRED' and result['read_only']
    assert result['requires_manual_approval'] and result['executable_manifest'] is None
    assert result['prepare_or_execute_authorized'] is False
    assert result['candidate_moves'][0]['from']=='apps/xbs'
    assert any(r['path']=='.github/workflows/build.yml' and r['line']==2 and r['classification']=='must_rewrite' for r in result['references'])
    assert any(r['path']=='notes.md' and r['classification']=='likely_reference_review' for r in result['references'])
    assert result['generated_backups'][0]['classification']=='generated_backup'
    assert not (tmp_path/'should_not_exist').exists()
    assert old==(git(src,'status','--porcelain'),git(dst,'status','--porcelain'),git(src,'rev-parse','HEAD'))
    assert result==discover(path)  # deterministic, no volatile timestamps


def test_destination_external_consumer_and_no_credential_echo(tmp_path):
    src,dst,path=example(tmp_path,consumer='export API_TOKEN=super-secret-value; cd apps/xbs')
    out=discover(path)
    assert any(r['classification']=='external_consumer_unknown' for r in out['references'])
    serialized=json.dumps(out)
    assert 'super-secret-value' not in serialized and 'API_TOKEN' not in serialized
    assert out['references'][0]['line_sha256']


def test_ambiguous_substring_rejected_and_exact_path_matched(tmp_path):
    src,dst,path=example(tmp_path,reference='apps/xbs-extra')
    out=discover(path)
    assert not any(r['path']=='.github/workflows/build.yml' for r in out['references'])
    assert not any(r['path']=='notes.md' for r in out['references'])
    assert any(r['classification']=='irrelevant' and r['reason']=='identifier_boundary_rejected'
               for r in out['irrelevant_matches'])


def test_relative_import_or_module_signal(tmp_path):
    src,dst,path=example(tmp_path)
    (src/'apps/xbs/go.mod').write_text('module example.org/xbs\nreplace core => ../apps/xbs\n')
    git(src,'add','.');git(src,'commit','-qm','relative')
    repin(path,src)
    out=discover(path)
    assert any(r['path']=='apps/xbs/go.mod' and r['classification']=='must_rewrite' and
               r['signal']=='relative_import_or_module' for r in out['references'])


def test_explicit_py_import_path_review(tmp_path):
    src,dst,path=example(tmp_path)
    (src/'importer.py').write_text('from apps.xbs import client\n')
    git(src,'add','.');git(src,'commit','-qm','imports')
    repin(path,src)
    out=discover(path)
    assert any(r['path']=='importer.py' and r['signal']=='python_import' and
               r['classification']=='likely_reference_review' for r in out['references'])
    # Dotted imports are ambiguous, so the scanner must not falsely authorize a rewrite.
    assert out['prepare_or_execute_authorized'] is False


def test_oversized_and_binary_are_not_silently_clean(tmp_path):
    src,dst,path=example(tmp_path)
    (src/'huge.md').write_text('A' * (256*1024+1))
    (src/'binary.dat').write_bytes(b'abc\0apps/xbs')
    git(src,'add','.');git(src,'commit','-qm','binary and huge')
    repin(path,src)
    out=discover(path)
    assert not out['scan_complete']
    assert {x['reason'] for x in out['unscanned']} >= {'oversized_unscanned','binary_or_oversized_unscanned'}


def test_symlink_tracked_is_not_dereferenced(tmp_path):
    src,dst,path=example(tmp_path)
    (src/'bad.link').symlink_to('/etc/passwd')
    git(src,'add','.');git(src,'commit','-qm','symlink')
    repin(path,src)
    out=discover(path)
    assert any(x['path']=='bad.link' and x['reason']=='symlink_or_nonregular_tracked_file' for x in out['unscanned'])


def test_ignored_symlink_fails_closed(tmp_path):
    src,dst,path=example(tmp_path)
    (src/'apps/xbs/bad.tmp').symlink_to('/etc/passwd')
    with pytest.raises(ExtractionBlocked,match='symlink path refused|unsafe ignored'):
        discover(path)


def test_dirty_and_source_drift_rejected(tmp_path):
    src,dst,path=example(tmp_path)
    (src/'notes.md').write_text('tampered')
    with pytest.raises(ExtractionBlocked,match='dirty'):
        discover(path)
    git(src,'add','.');git(src,'commit','-qm','drift')
    with pytest.raises(ExtractionBlocked,match='head changed'):
        discover(path)


def test_destination_drift_rejected(tmp_path):
    src,dst,path=example(tmp_path)
    git(dst,'commit','--allow-empty','-qm','next')
    with pytest.raises(ExtractionBlocked,match='head changed'):
        discover(path)


def test_nested_repository_rejected(tmp_path):
    src,dst,path=example(tmp_path)
    nested=src/'apps/xbs/.git'
    nested.mkdir()
    with pytest.raises(ExtractionBlocked,match='nested repository'):
        discover(path)


def test_discovery_does_not_override_prepare_safety(tmp_path):
    src,dst,path=example(tmp_path)
    assert discover(path)['ok']
    # Existing execution engine independently rejects dangling references.
    result=run('plan',path,tmp_path/'state')
    assert not result['ok'] and 'dangling' in result['reason']
    assert not (dst/'main.go').exists()


def test_discovery_does_not_mutate_pending_partial_commit(tmp_path):
    src,dst,path=example(tmp_path,reference='none')
    # No prepare/execute effects; escrow and Git refs remain unchanged.
    h=git(dst,'rev-parse','HEAD')
    discover(path)
    assert git(dst,'rev-parse','HEAD')==h


