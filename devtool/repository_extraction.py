"""NEXT-06: bounded source-locked two-checkout extraction, not a cross-repo Git transaction.

No network actions or Git reset are performed. Generated bytes are escrowed before the
first checkout mutation. A destination commit may precede a blocked source commit;
this is recorded as partial success, never auto-rolled back.
"""
from __future__ import annotations

import argparse
from contextlib import contextmanager
import fcntl
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import stat
import subprocess
import tempfile
from typing import Any, Iterator

SCHEMA = "devtool.repo-extraction.v1"
SHA = re.compile(r"[0-9a-f]{40,64}\Z")
TOKEN = re.compile(r"[a-zA-Z0-9_-]{1,80}\Z")
MAX_TRACKED = 5000
MAX_GENERATED = 10000
MAX_BACKUP_BYTES = 2 * 1024**3
MAX_FILE = 512 * 1024**2

class ExtractionBlocked(RuntimeError):
    """Preflight or checked execution rejected an unsafe source state."""


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _file_sha(path: Path, max_bytes: int = MAX_FILE) -> str:
    digest=hashlib.sha256()
    fd=os.open(str(path),os.O_RDONLY|os.O_NOFOLLOW)
    try:
        info=os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_size > max_bytes:
            raise ExtractionBlocked(f"unacceptable file type or size: {path.name}")
        with os.fdopen(fd,"rb",closefd=False) as source:
            while True:
                chunk=source.read(1024*1024)
                if not chunk:break
                digest.update(chunk)
    finally:os.close(fd)
    return digest.hexdigest()


def _git(root: Path, *args: str, binary: bool = False, check: bool = True) -> bytes | str:
    cmd = ["git", "-C", str(root), *args]
    result = subprocess.run(cmd, capture_output=True, timeout=120)
    if result.returncode and check:
        raise ExtractionBlocked(f"Git {args[0]} refused: {result.stderr.decode('utf-8','replace')[:250]}")
    return result.stdout if binary else result.stdout.decode("utf-8", "replace").strip()


def _rel(name: str, *, dot: bool = False) -> str:
    if dot and name == ".":
        return ""
    if not isinstance(name, str) or not name or "\\" in name or name.startswith("/"):
        raise ExtractionBlocked(f"unsafe relative path: {name!r}")
    path = PurePosixPath(name)
    if any(p in (".", "..", "", ".git") for p in name.split("/")) or str(path) != name or name.startswith("-"):
        raise ExtractionBlocked(f"unsafe relative path: {name!r}")
    return name


def _safe(root: Path, name: str, *, missing: bool = True) -> Path:
    _rel(name)
    p = root
    for part in name.split("/"):
        p = p / part
        if p.is_symlink():
            raise ExtractionBlocked(f"symlink path refused: {name}")
        if p.exists() and not (p.is_dir() or p.is_file()):
            raise ExtractionBlocked(f"special file refused: {name}")
    if not missing and not p.is_file():
        raise ExtractionBlocked(f"source file missing: {name}")
    return p


def _read_manifest(file: Path) -> dict[str, Any]:
    if file.is_symlink() or not file.is_file() or file.stat().st_size > 2_000_000:
        raise ExtractionBlocked("manifest must be a bounded regular file")
    data = json.loads(file.read_text())
    if not isinstance(data, dict) or data.get("schema") != SCHEMA:
        raise ExtractionBlocked("unsupported extraction manifest")
    if set(data) - {"schema", "source", "destination", "moves", "source_rewrites", "destination_rewrites", "generated_paths", "forbid_source_references", "reference_allowlist", "preserve_history", "clean_ignored"}:
        raise ExtractionBlocked("unknown extraction manifest fields")
    a, b = data.get("source"), data.get("destination")
    if not isinstance(a, dict) or not isinstance(b, dict):
        raise ExtractionBlocked("source and destination identities required")
    for row in (a, b):
        if set(row) != {"path", "head", "tree", "branch", "remote", "remote_url"}:
            raise ExtractionBlocked("exact Git identity fields required")
        p = Path(row["path"])
        if not p.is_absolute() or not p.is_dir() or p.is_symlink():
            raise ExtractionBlocked("two absolute existing nonsymlink repository roots required")
        if not SHA.fullmatch(str(row["head"])) or not SHA.fullmatch(str(row["tree"])):
            raise ExtractionBlocked("pinned Git head and tree SHAs required")
        for name in ("branch", "remote", "remote_url"):
            if not isinstance(row[name], str) or not row[name].strip():
                raise ExtractionBlocked(f"missing Git {name}")
    pa, pb = Path(a["path"]).resolve(), Path(b["path"]).resolve()
    if pa == pb or pa in pb.parents or pb in pa.parents:
        raise ExtractionBlocked("repositories must be disjoint")
    moves = data.get("moves")
    if not isinstance(moves, list) or not 1 <= len(moves) <= 32:
        raise ExtractionBlocked("one to 32 directory extractions required")
    srcs, dsts = [], []
    for row in moves:
        if not isinstance(row, dict) or set(row) != {"from", "to"}:
            raise ExtractionBlocked("move needs from/to directory prefixes")
        x, y = _rel(row["from"]), _rel(row["to"], dot=True)
        if any(x == n or x.startswith(n + "/") or n.startswith(x + "/") for n in srcs):
            raise ExtractionBlocked("overlapping source prefixes")
        if any(y == n or y.startswith(n + "/") or n.startswith(y + "/") for n in dsts):
            raise ExtractionBlocked("overlapping destination prefixes")
        srcs.append(x); dsts.append(y)
    for key in ("source_rewrites", "destination_rewrites"):
        rows = data.get(key, [])
        if not isinstance(rows, list) or len(rows) > 256:
            raise ExtractionBlocked("bounded declarative rewrites required")
        for item in rows:
            if not isinstance(item, dict) or set(item) != {"path", "old", "new"}:
                raise ExtractionBlocked("rewrite needs exact path/old/new")
            _rel(item["path"])
            if not all(isinstance(item[q], str) for q in ("old", "new")) or not item["old"] or len(item["old"]) > 5000 or len(item["new"]) > 5000:
                raise ExtractionBlocked("invalid bounded rewrite")
    for key in ("generated_paths", "forbid_source_references", "reference_allowlist"):
        vals = data.get(key, [])
        if not isinstance(vals, list) or len(vals) > 10000 or not all(isinstance(x, str) for x in vals):
            raise ExtractionBlocked(f"invalid {key}")
        if key != "forbid_source_references":
            for x in vals: _rel(x)
        elif any(not x or len(x) > 250 for x in vals):
            raise ExtractionBlocked("invalid reference search token")
    if not data.get("forbid_source_references"):
        raise ExtractionBlocked("declare forbidden source references for orphan detection")
    for key in ("preserve_history", "clean_ignored"):
        if key in data and not isinstance(data[key], bool):
            raise ExtractionBlocked(f"{key} must be a boolean")
    return data


def _identity(root: Path, lock: dict[str, Any]) -> None:
    if _git(root, "rev-parse", "--show-toplevel") != str(root.resolve()):
        raise ExtractionBlocked("repository worktree root mismatch")
    for arg, key in (("HEAD", "head"), ("HEAD^{tree}", "tree")):
        if _git(root, "rev-parse", arg) != lock[key]:
            raise ExtractionBlocked(f"{root.name} {key} changed")
    if _git(root, "symbolic-ref", "--quiet", "--short", "HEAD") != lock["branch"]:
        raise ExtractionBlocked("branch changed")
    if _git(root, "remote", "get-url", lock["remote"]) != lock["remote_url"]:
        raise ExtractionBlocked("remote URL changed (local equality, not remote ownership proof)")


def _tracked(root: Path) -> list[str]:
    raw = _git(root, "ls-files", "-z", binary=True)
    return [s.decode("utf-8", "strict") for s in raw.split(b"\0") if s]


def _ignored(root: Path, prefixes: list[str]) -> list[str]:
    raw = _git(root, "ls-files", "--others", "--ignored", "--exclude-standard", "-z", "--", *prefixes, binary=True)
    return sorted({p.decode("utf-8", "strict") for p in raw.split(b"\0") if p})


def _untracked(root: Path, prefixes: list[str]) -> list[str]:
    raw = _git(root, "ls-files", "--others", "--exclude-standard", "-z", "--", *prefixes, binary=True)
    return [p.decode("utf-8", "strict") for p in raw.split(b"\0") if p]


def _rewrite(payload: bytes, changes: list[dict[str, str]], filename: str) -> bytes:
    for row in changes:
        try:
            old, new = row["old"].encode(), row["new"].encode()
        except UnicodeError as exc:
            raise ExtractionBlocked(f"invalid rewrite encoding in {filename}") from exc
        if payload.count(old) != 1:
            raise ExtractionBlocked(f"rewrite not uniquely present in {filename}: {row['old'][:50]}")
        payload = payload.replace(old, new, 1)
    return payload


def _transaction_free(root: Path) -> None:
    from .overlay.recovery import overlay_recovery_plan
    recovery = overlay_recovery_plan(root, limit=25)
    if recovery.get("marker_issues") or recovery.get("active_transactions"):
        raise ExtractionBlocked("unresolved Devtool transaction markers; review before extraction")


def _candidate(config: dict[str, Any]) -> dict[str, Any]:
    source, dest = (Path(config[k]["path"]).resolve() for k in ("source", "destination"))
    _identity(source, config["source"]); _identity(dest, config["destination"])
    for root in (source, dest):
        _transaction_free(root)
        if _git(root, "status", "--porcelain=v1", "--untracked-files=all"):
            raise ExtractionBlocked(f"{root.name} is dirty, including unknown untracked files")
        if _git(root, "ls-files", "--stage").find("160000 ") >= 0:
            raise ExtractionBlocked("nested Git submodule refused")
    srcfiles, dstfiles = _tracked(source), set(_tracked(dest))
    prefixes = [m["from"] for m in config["moves"]]
    if _untracked(source, prefixes):
        raise ExtractionBlocked("unknown untracked source: " + repr(_untracked(source, prefixes)[:8]))
    ignored = _ignored(source, prefixes)
    for name in config.get("generated_paths", []):
        _safe(source, name)
        if name not in _ignored(source, [name]) or not (source/name).is_file():
            raise ExtractionBlocked(f"additional generated path is not an ignored regular file: {name}")
        ignored.append(name)
    ignored = sorted(set(ignored))
    if len(ignored) > MAX_GENERATED: raise ExtractionBlocked("generated inventory exceeds bound")
    for name in ignored: _safe(source, name, missing=False)
    transfers: dict[str, str] = {}
    for move in config["moves"]:
        old, new = move["from"], "" if move["to"] == "." else move["to"]
        chosen = [f for f in srcfiles if f.startswith(old + "/")]
        if not chosen: raise ExtractionBlocked(f"source prefix has no Git-owned files: {old}")
        for filename in chosen:
            rest = filename[len(old)+1:]
            target = f"{new}/{rest}" if new else rest
            _rel(target); _safe(source, filename, missing=False); _safe(dest, target)
            if filename in transfers or target in transfers.values() or target in dstfiles or (dest/target).exists():
                raise ExtractionBlocked(f"destination collision: {target}")
            if (source/filename).stat().st_size > MAX_FILE:
                raise ExtractionBlocked("tracked source file too large")
            transfers[filename] = target
    if len(transfers) > MAX_TRACKED: raise ExtractionBlocked("tracked transfer exceeds bound")
    bysrc: dict[str,list[dict[str,str]]] = {}
    bydst: dict[str,list[dict[str,str]]] = {}
    for row in config.get("source_rewrites", []): bysrc.setdefault(row["path"],[]).append(row)
    for row in config.get("destination_rewrites", []): bydst.setdefault(row["path"],[]).append(row)
    newdst: dict[str,bytes] = {}
    for src, target in transfers.items():
        payload = (source/src).read_bytes()
        newdst[target] = _rewrite(payload, bydst.pop(target, []), target)
    if bydst: raise ExtractionBlocked(f"destination rewrite not in transferred files: {sorted(bydst)}")
    remaining: dict[str, bytes] = {}
    for path, changes in bysrc.items():
        if path not in srcfiles or path in transfers:
            raise ExtractionBlocked("source rewrite must be a remaining tracked file: " + path)
        _safe(source,path,missing=False)
        remaining[path] = _rewrite((source/path).read_bytes(), changes, path)
    # All source-owned paths must be accounted for; otherwise hidden dependencies stay behind.
    forbidden = config["forbid_source_references"]
    allow = set(config.get("reference_allowlist", []))
    for path in srcfiles:
        if path in transfers: continue
        _safe(source,path,missing=False)
        payload = remaining.get(path)
        if payload is None:
            p = source/path
            if p.stat().st_size > 3_000_000:
                if path not in allow:
                    raise ExtractionBlocked(f"oversized unscanned source for orphan analysis: {path}")
                continue
            payload = p.read_bytes()
        if path not in allow and b"\0" not in payload and any(word.encode() in payload for word in forbidden):
            raise ExtractionBlocked(f"dangling extracted-target reference: {path}")
    # Go module ownership cannot rely on inherited monorepo relative traversal.
    for name, payload in newdst.items():
        if name.endswith(("go.mod", "go.work")) and (b"../.." in payload or b"replace ../" in payload):
            raise ExtractionBlocked(f"inherited Go module path remains: {name}")
    modes: dict[str,str] = {}
    for name in transfers:
        index = _git(source,"ls-files","--stage","--",name).split(" ",1)[0]
        if index not in ("100644","100755"):
            raise ExtractionBlocked(f"unsupported Git file mode for extraction: {name}")
        modes[transfers[name]]=index
    sizes = {name:(source/name).stat().st_size for name in ignored}
    if sum(sizes.values()) > MAX_BACKUP_BYTES or any(v > MAX_FILE for v in sizes.values()):
        raise ExtractionBlocked("generated data exceeds bounded escrow capacity")
    hashes = {name:_file_sha(source/name) for name in ignored}
    return {"source":source,"destination":dest,"transfer":transfers,"destination_bytes":newdst,
            "source_bytes":remaining,"ignored":ignored,"ignored_hashes":hashes,"ignored_sizes":sizes,
            "source_paths":sorted([*transfers, *remaining]),"destination_paths":sorted(newdst),"destination_modes":modes}


def _external(state_dir: Path, roots: tuple[Path,Path]) -> Path:
    if not state_dir.is_absolute() or state_dir.is_symlink(): raise ExtractionBlocked("absolute non-symlink state directory required")
    resolved = state_dir.resolve()
    for root in roots:
        if resolved == root or root in resolved.parents or resolved in root.parents:
            raise ExtractionBlocked("state must be external to BOTH Git repositories")
    return resolved


def _state_paths(file: Path, state_dir: Path, config: dict[str, Any]) -> tuple[Path,Path,str]:
    raw = json.dumps(config,sort_keys=True,separators=(",", ":")).encode()
    digest = _sha(raw)
    root = _external(state_dir,(Path(config["source"]["path"]).resolve(),Path(config["destination"]["path"]).resolve()))
    return root / digest[:24], root, digest


def _load_receipt(path: Path, digest: str) -> dict[str, Any] | None:
    f = path/"journal.json"
    if not f.exists(): return None
    if f.is_symlink(): raise ExtractionBlocked("journal symlink refused")
    value = json.loads(f.read_text())
    if value.get("manifest_sha256") != digest or value.get("schema") != SCHEMA:
        raise ExtractionBlocked("journal manifest identity differs")
    return value


def _atomic(path: Path, raw: bytes) -> None:
    fd,tmp = tempfile.mkstemp(prefix=".tmp-", dir=path.parent)
    try:
        with os.fdopen(fd,"wb") as out:
            out.write(raw);out.flush();os.fsync(out.fileno())
        os.replace(tmp,path)
        dirfd = os.open(str(path.parent),os.O_RDONLY)
        try:os.fsync(dirfd)
        finally:os.close(dirfd)
    finally:
        if os.path.exists(tmp):os.unlink(tmp)


def _write_journal(base: Path, value: dict[str, Any]) -> None:
    _atomic(base/"journal.json", (json.dumps(value,indent=2,sort_keys=True)+"\n").encode())


@contextmanager
def _lock(base: Path) -> Iterator[None]:
    base.mkdir(parents=True,exist_ok=True)
    if base.is_symlink(): raise ExtractionBlocked("state symlink refused")
    f = base/".lock"
    fd = os.open(f,os.O_RDWR|os.O_CREAT|os.O_NOFOLLOW,0o600)
    try:
        fcntl.flock(fd,fcntl.LOCK_EX|fcntl.LOCK_NB)
        yield
    except BlockingIOError as exc:
        raise ExtractionBlocked("another extraction owns the journal") from exc
    finally:
        os.close(fd)


def _verify_backup(config: dict[str,Any], candidate: dict[str,Any], base:Path, journal:dict[str,Any]) -> None:
    saved = journal.get("generated", {})
    if set(saved)!=set(candidate["ignored"]):
        raise ExtractionBlocked("generated escrow inventory drifted")
    for name in candidate["ignored"]:
        escrow=_safe(base,"generated/"+name)
        if not escrow.is_file():raise ExtractionBlocked(f"missing generated backup {name}")
        if _file_sha(escrow) != saved[name]["sha256"] or escrow.stat().st_size != saved[name]["size"]:
            raise ExtractionBlocked(f"tampered generated backup {name}")
        original=_safe(candidate["source"],name)
        if not original.exists() and journal.get("ignored_cleaned") and config.get("clean_ignored"):
            continue
        if not original.is_file() or _file_sha(original) != saved[name]["sha256"]:
            raise ExtractionBlocked(f"generated source changed after backup {name}")
    bundle = journal.get("history")
    if bundle:
        file=base/"source-history.bundle"
        if not file.is_file() or file.is_symlink() or _file_sha(file, 4 * 1024**3) != bundle["sha256"]:
            raise ExtractionBlocked("Git history escrow integrity failure")


def _escrow(config:dict[str,Any], candidate:dict[str,Any], base:Path, digest:str) -> dict[str,Any]:
    if (base/"journal.json").exists():raise ExtractionBlocked("journal already exists")
    temp = base/".preparing"
    if temp.exists(): raise ExtractionBlocked("interrupted escrow requires manual inspection")
    temp.mkdir()
    records:dict[str,Any]={}
    try:
        for name in candidate["ignored"]:
            original=_safe(candidate["source"],name,missing=False)
            if original.stat().st_size != candidate["ignored_sizes"][name]:raise ExtractionBlocked("generated size changed")
            target=temp/"generated"/name
            target.parent.mkdir(parents=True,exist_ok=True)
            srcfd=os.open(str(original),os.O_RDONLY|os.O_NOFOLLOW)
            try:
                srcstat=os.fstat(srcfd)
                if not stat.S_ISREG(srcstat.st_mode):raise ExtractionBlocked("generated source must be regular")
                with os.fdopen(srcfd,"rb",closefd=False) as src, target.open("xb") as dst:
                    h=hashlib.sha256()
                    while True:
                        chunk=src.read(1024*1024)
                        if not chunk:break
                        h.update(chunk);dst.write(chunk)
                    dst.flush();os.fsync(dst.fileno())
            finally:os.close(srcfd)
            if h.hexdigest()!=candidate["ignored_hashes"][name]:raise ExtractionBlocked("generated hash changed mid-backup")
            records[name]={"sha256":h.hexdigest(),"size":target.stat().st_size}
        history=None
        if config.get("preserve_history",False):
            target=temp/"source-history.bundle"
            _git(candidate["source"],"bundle","create",str(target),"--all")
            if not target.is_file(): raise ExtractionBlocked("Git bundle escrow missing")
            history={"sha256":_file_sha(target, 4 * 1024**3),"scope":"source git refs; not grafted to destination"}
        # No Git mutation has occurred. Escrow files become durable before journal publication.
        for item in temp.iterdir():
            os.replace(item,base/item.name)
        temp.rmdir()
        journal={"schema":SCHEMA,"manifest_sha256":digest,"phase":"PREPARED",
                 "source_initial_head":config["source"]["head"],"destination_initial_head":config["destination"]["head"],
                 "source_commit":None,"destination_commit":None,"generated":records,"history":history,
                 "source_paths":candidate["source_paths"],"destination_paths":candidate["destination_paths"],
                 "source_output_sha256":{p:_sha(data) for p,data in candidate["source_bytes"].items()},
                 "destination_output_sha256":{p:_sha(data) for p,data in candidate["destination_bytes"].items()},
                 "destination_modes":candidate["destination_modes"], "ignored_cleaned":False,
                 "cross_repo_atomic":False,"release_qualified":False}
        _write_journal(base,journal)
        return journal
    finally:
        if temp.exists():shutil.rmtree(temp)


def _status_paths(repo:Path) -> set[str]:
    raw=_git(repo,"status","--porcelain=v1","-z","--untracked-files=all",binary=True)
    result:set[str]=set()
    records=raw.split(b"\0");i=0
    while i<len(records):
        entry=records[i]
        if not entry: i+=1;continue
        if len(entry)<4:raise ExtractionBlocked("unparseable Git status")
        result.add(entry[3:].decode("utf8","strict"))
        if entry[:1] in (b"R",b"C") or entry[1:2] in (b"R",b"C"):
            i+=1
            if i<len(records):result.add(records[i].decode("utf8","strict"))
        i+=1
    return result


def _commit_scoped(repo:Path, paths:list[str], subject:str) -> str:
    _git(repo,"add","-A","--",*paths)
    _git(repo,"-c","core.hooksPath=/dev/null","commit","-m",subject,"--no-gpg-sign","--",*paths)
    return str(_git(repo,"rev-parse","HEAD"))


def _committed(repo:Path, source_head:str, expected:dict[str,str], removed:list[str], subject:str, modes:dict[str,str]|None=None) -> bool:
    if _git(repo,"rev-parse","HEAD^") != source_head:return False
    if _git(repo,"log","-1","--format=%s") != subject:return False
    changed=set(str(_git(repo,"diff-tree","--no-commit-id","--name-only","-r","HEAD")).splitlines())
    if changed != set(expected)|set(removed):return False
    for name,digest in expected.items():
        f=_safe(repo,name,missing=False)
        if _sha(f.read_bytes())!=digest:return False
        if modes and name in modes:
            mode=_git(repo,"ls-files","--stage","--",name).split(" ",1)[0]
            if mode!=modes[name]:return False
    for name in removed:
        if _safe(repo,name).exists():return False
    return not _status_paths(repo)


def _check_mutation_candidate(config:dict[str,Any], cand:dict[str,Any], journal:dict[str,Any], side:str) -> str:
    row=config[side];repo=cand[side]
    # Return FRESH, APPLIED, COMMITTED or refuse everything else.
    _identity_stable(repo,row)
    commit=journal.get(side+"_commit")
    subject=f"devtool: NEXT-06 extract {side} {journal['manifest_sha256'][:12]}"
    expected=journal[side+"_output_sha256"]
    removed = sorted(cand["transfer"]) if side=="source" else []
    if commit:
        if _git(repo,"rev-parse","HEAD")!=commit or not _committed(repo,row["head"],expected,removed,subject,journal["destination_modes"] if side=="destination" else None):
            raise ExtractionBlocked(f"committed {side} changed since receipt")
        return "COMMITTED"
    head=_git(repo,"rev-parse","HEAD")
    if head!=row["head"]:
        if _committed(repo,row["head"],expected,removed,subject,journal["destination_modes"] if side=="destination" else None):return "COMMITTED_UNRECORDED"
        raise ExtractionBlocked(f"unrecognized {side} commit; manual recovery required")
    edits=cand["source_bytes"] if side=="source" else cand["destination_bytes"]
    modified=_status_paths(repo)
    if not modified:return "FRESH"
    if not modified.issubset(set(cand[side+"_paths"])):
        raise ExtractionBlocked(f"unexpected partial {side} worktree paths: {sorted(modified)[:8]}")
    for name, data in edits.items():
        path=_safe(repo,name)
        current=path.read_bytes() if path.is_file() else None
        if name in modified:
            if current is None or _sha(current)!=_sha(data):
                raise ExtractionBlocked(f"modified partial {side} output: {name}")
        else:
            if (side=="destination" and current is not None) or (side=="source" and current!=_git(repo,"show",row["head"]+":"+name,binary=True)):
                raise ExtractionBlocked(f"unrecognized partial {side} state: {name}")
    for name in removed:
        path=_safe(repo,name)
        if name in modified and path.exists():raise ExtractionBlocked(f"modified partial source deletion: {name}")
        if name not in modified and not path.is_file():raise ExtractionBlocked(f"unrecognized missing source path: {name}")
    return "APPLIED_UNCOMMITTED" if modified==set(cand[side+"_paths"]) else "PARTIAL_OWNED"


def _identity_stable(repo:Path,lock:dict[str,Any]) -> None:
    if _git(repo,"symbolic-ref","--quiet","--short","HEAD")!=lock["branch"] or _git(repo,"remote","get-url",lock["remote"])!=lock["remote_url"]:
        raise ExtractionBlocked("branch/remote changed after prepare")


def _candidate_from_baseline(config:dict[str,Any],journal:dict[str,Any]) -> dict[str,Any]:
    """Re-evaluate candidate against exact original Git commits in disposable worktrees.

    We use git show for tracked files when a side has already committed, so an earlier
    destination commit does not change the planned source/destination contract.
    """
    src,dst=(Path(config[k]["path"]).resolve() for k in ("source","destination"))
    # For intermediate states, original tracked files are obtained via Git object IDs.
    # This is only used after a PREPARED journal, so recheck pinned tree against objects.
    for side,root in (("source",src),("destination",dst)):
        if _git(root,"rev-parse",config[side]["head"]+"^{tree}")!=config[side]["tree"]:
            raise ExtractionBlocked("original source tree object changed")
    transfers={}
    srcfiles=[n.decode() for n in _git(src,"ls-tree","-r","--name-only","-z",config["source"]["head"],binary=True).split(b"\0") if n]
    dstfiles=set(n.decode() for n in _git(dst,"ls-tree","-r","--name-only","-z",config["destination"]["head"],binary=True).split(b"\0") if n)
    for move in config["moves"]:
        x=move["from"];y="" if move["to"]=="." else move["to"]
        for old in srcfiles:
            if old.startswith(x+"/"):
                new=(y+"/" if y else "")+old[len(x)+1:]
                if new in dstfiles or new in transfers.values():raise ExtractionBlocked("tracked target collision")
                transfers[old]=new
    if not transfers:raise ExtractionBlocked("no tracked source files")
    bysrc={};bydst={}
    for row in config.get("source_rewrites",[]):bysrc.setdefault(row["path"],[]).append(row)
    for row in config.get("destination_rewrites",[]):bydst.setdefault(row["path"],[]).append(row)
    dstbytes={};modes={}
    for old,new in transfers.items():
        raw=_git(src,"show",config["source"]["head"]+":"+old,binary=True)
        dstbytes[new]=_rewrite(raw,bydst.pop(new,[]),new)
        info=_git(src,"ls-tree",config["source"]["head"],"--",old)
        mode=info.split(" ",1)[0]
        if mode not in ("100644","100755"):raise ExtractionBlocked(f"unsupported source Git mode: {old}")
        modes[new]=mode
    if bydst:raise ExtractionBlocked("unknown destination rewrite")
    srcbytes={}
    for name,rows in bysrc.items():
        raw=_git(src,"show",config["source"]["head"]+":"+name,binary=True)
        srcbytes[name]=_rewrite(raw,rows,name)
    result={"source":src,"destination":dst,"transfer":transfers,"source_bytes":srcbytes,"destination_bytes":dstbytes,
            "source_paths":sorted([*transfers,*srcbytes]),"destination_paths":sorted(dstbytes),"destination_modes":modes,
            "ignored":sorted(journal["generated"]),"ignored_hashes":{k:v["sha256"] for k,v in journal["generated"].items()},
            "ignored_sizes":{k:v["size"] for k,v in journal["generated"].items()}}
    if journal.get("destination_modes") != modes:
        raise ExtractionBlocked("prepared Git executable mode drift")
    for side in ("source","destination"):
        if journal.get(side+"_output_sha256") != {p:_sha(data) for p,data in result[side+"_bytes"].items()} or journal.get(side+"_paths")!=result[side+"_paths"]:
            raise ExtractionBlocked("prepared output contract drift")
    return result


def plan(manifest:Path,state_dir:Path) -> dict[str,Any]:
    config=_read_manifest(manifest)
    base,root,digest=_state_paths(manifest,state_dir,config)
    journal=_load_receipt(base,digest)
    try:
        if journal is None:
            cand=_candidate(config)
            state="READY"
            details={"tracked_moves":len(cand["transfer"]),"generated_files":len(cand["ignored"]),
                     "backup_bytes":sum(cand["ignored_sizes"].values()),"source_pruning":cand["source_paths"],
                     "destination_outputs":cand["destination_paths"]}
        else:
            cand=_candidate_from_baseline(config,journal)
            _verify_backup(config,cand,base,journal)
            side_status={side:_check_mutation_candidate(config,cand,journal,side)
                         for side in ("destination","source")}
            details={"source_paths":cand["source_paths"],"destination_paths":cand["destination_paths"],
                     "source_commit":journal["source_commit"],"destination_commit":journal["destination_commit"],
                     "repositories":side_status,
                     "generated_escrow":str(base/"generated"),
                     "generated_cleaned":bool(journal.get("ignored_cleaned"))}
            state=journal["phase"]
        return {"schema":SCHEMA,"ok":True,"state":state,"read_only":True,"manifest_sha256":digest,
                "cross_repo_atomic":False,"release_qualified":False,**details}
    except (ExtractionBlocked,OSError) as exc:
        return {"schema":SCHEMA,"ok":False,"state":"BLOCKED","reason":str(exc),"read_only":True,
                "cross_repo_atomic":False,"release_qualified":False}


def run(operation:str,manifest:Path,state_dir:Path,*,yes:bool=False) -> dict[str,Any]:
    if operation in ("plan","status"):return plan(manifest,state_dir)
    if not yes:raise ExtractionBlocked("prepare/execute/resume requires explicit --yes")
    config=_read_manifest(manifest)
    base,root,digest=_state_paths(manifest,state_dir,config)
    with _lock(base):
        journal=_load_receipt(base,digest)
        if operation=="prepare":
            if journal:raise ExtractionBlocked("already prepared; use execute or status")
            cand=_candidate(config)
            journal=_escrow(config,cand,base,digest)
            return {"schema":SCHEMA,"ok":True,"state":"PREPARED","backup_files":len(journal["generated"]),
                    "history_escrow":bool(journal["history"]),"cross_repo_atomic":False,"release_qualified":False}
        if not journal:raise ExtractionBlocked("prepare must complete before execute/resume")
        cand=_candidate_from_baseline(config,journal)
        _verify_backup(config,cand,base,journal)
        # Revalidate BOTH Git owners before the first write of this invocation.
        # Prevent a newly dirty source being discovered only after destination commit.
        for side in ("destination", "source"):
            _transaction_free(cand[side])
            _check_mutation_candidate(config,cand,journal,side)
        # Make the destination durable first; never remove the source until it commits.
        for side in ("destination","source"):
            state=_check_mutation_candidate(config,cand,journal,side)
            repo=cand[side]
            if side=="source" and not journal.get("destination_commit"):
                raise ExtractionBlocked("source cannot prune before verified destination commit")
            subject=f"devtool: NEXT-06 extract {side} {digest[:12]}"
            if state=="COMMITTED_UNRECORDED":
                journal[side+"_commit"]=_git(repo,"rev-parse","HEAD")
                journal["phase"]="DEST_COMMITTED" if side=="destination" else "COMPLETE"
                _write_journal(base,journal)
                continue
            if state=="COMMITTED":continue
            if state in ("FRESH","PARTIAL_OWNED"):
                if side=="destination":
                    for name,payload in cand["destination_bytes"].items():
                        target=_safe(repo,name)
                        target.parent.mkdir(parents=True,exist_ok=True)
                        if target.exists():
                            if _sha(target.read_bytes())!=_sha(payload):
                                raise ExtractionBlocked("destination changed during staging: "+name)
                        else:
                            with target.open("xb") as f:f.write(payload);f.flush();os.fsync(f.fileno())
                        if cand["destination_modes"][name]=="100755":os.chmod(target,0o755)
                else:
                    for name,payload in cand["source_bytes"].items():
                        target=_safe(repo,name,missing=False)
                        if target.read_bytes()!=payload:target.write_bytes(payload)
                    for name in cand["transfer"]:
                        target=_safe(repo,name)
                        if target.exists():target.unlink()
            if _status_paths(repo)!=set(cand[side+"_paths"]):
                raise ExtractionBlocked(f"{side} staging differs from prepared scope")
            if not all(_sha(_safe(repo,p,missing=False).read_bytes())==_sha(payload)
                       for p,payload in cand[side+"_bytes"].items()):
                raise ExtractionBlocked(f"{side} output tamper before commit")
            newhead=_commit_scoped(repo,cand[side+"_paths"],subject)
            if not _committed(repo,config[side]["head"],journal[side+"_output_sha256"],
                              list(cand["transfer"]) if side=="source" else [],subject,
                              cand["destination_modes"] if side=="destination" else None):
                raise ExtractionBlocked(f"{side} new commit did not match intent")
            journal[side+"_commit"]=newhead
            journal["phase"]="DEST_COMMITTED" if side=="destination" else "COMPLETE"
            _write_journal(base,journal)
        # Any generated files are only removed after BOTH source and destination commits.
        if journal["source_commit"] and journal["destination_commit"] and config.get("clean_ignored",False) and not journal.get("ignored_cleaned"):
            for name,record in journal["generated"].items():
                path=_safe(cand["source"],name)
                if path.exists() and _file_sha(path)!=record["sha256"]:
                    raise ExtractionBlocked("generated file changed before optional cleanup")
            for name in journal["generated"]:
                path=_safe(cand["source"],name)
                if path.exists():path.unlink()
            journal["ignored_cleaned"]=True
            _write_journal(base,journal)
        return {"schema":SCHEMA,"ok":True,"state":journal["phase"],
                "source_commit":journal["source_commit"],"destination_commit":journal["destination_commit"],
                "generated_escrow":str(base/"generated"),"history_escrow":str(base/"source-history.bundle") if journal["history"] else None,
                "cross_repo_atomic":False,"release_qualified":False}


def main(argv:list[str]|None=None)->int:
    parser=argparse.ArgumentParser(description="Guarded two-checkout Git extraction")
    parser.add_argument("operation",choices=("plan","prepare","execute","resume","status"))
    parser.add_argument("manifest",type=Path)
    parser.add_argument("--state-dir",type=Path,default=Path.home()/".local/state/devtool/extractions")
    parser.add_argument("--yes",action="store_true")
    parser.add_argument("--json",action="store_true")
    args=parser.parse_args(argv)
    try:result=run(args.operation,args.manifest,args.state_dir,yes=args.yes)
    except (ExtractionBlocked,OSError,ValueError,RuntimeError) as exc:
        result={"schema":SCHEMA,"ok":False,"state":"BLOCKED","reason":str(exc),
                "cross_repo_atomic":False,"release_qualified":False}
    print(json.dumps(result,indent=2,sort_keys=True))
    return 0 if result["ok"] else 2

if __name__=="__main__":raise SystemExit(main())
